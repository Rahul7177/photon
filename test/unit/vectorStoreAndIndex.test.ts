import assert from "node:assert/strict";
import { describe, it } from "node:test";
import {
  VectorStore,
  normalize,
  dot,
  MAX_CHUNKS,
} from "../../src/core/index/vectorStore";

describe("Phase 5.2: VectorStore Fidelity, Validation & Model Migration", () => {
  describe("Model Identity & Invalidation", () => {
    it("invalidates and clears when persisted index is missing model identity but expected model is set", () => {
      const legacyData = {
        version: 1,
        dim: 3,
        chunks: [
          {
            path: "src/file1.ts",
            startLine: 1,
            endLine: 10,
            text: "legacy content",
            vector: [0.1, 0.2, 0.3],
          },
        ],
      };

      // Loading with expected model MUST invalidate because legacy data has no model identity
      const store = VectorStore.fromJSON(legacyData, "nomic-embed-text");
      assert.equal(store.stats.chunks, 0);
      assert.equal(store.getEmbeddingModel(), undefined);
    });

    it("invalidates when persisted model identity differs from expected model", () => {
      const persistedData = {
        version: 2,
        dim: 3,
        embeddingModel: "all-minilm",
        chunks: [
          {
            path: "src/file1.ts",
            startLine: 1,
            endLine: 10,
            text: "content",
            vector: [0.1, 0.2, 0.3],
          },
        ],
      };

      const store = VectorStore.fromJSON(persistedData, "nomic-embed-text");
      assert.equal(store.stats.chunks, 0);
    });

    it("loads cleanly when persisted model identity matches expected model", () => {
      const persistedData = {
        version: 2,
        dim: 3,
        embeddingModel: "nomic-embed-text",
        fileMtimes: { "src/file1.ts": 123456789 },
        fileSizes: { "src/file1.ts": 1024 },
        chunks: [
          {
            path: "src/file1.ts",
            startLine: 1,
            endLine: 10,
            text: "matching content",
            vector: [0.1, 0.2, 0.3],
          },
        ],
      };

      const store = VectorStore.fromJSON(persistedData, "nomic-embed-text");
      assert.equal(store.stats.chunks, 1);
      assert.equal(store.getFileMtime("src/file1.ts"), 123456789);
      assert.equal(store.getFileSize("src/file1.ts"), 1024);
      assert.equal(store.getEmbeddingModel(), "nomic-embed-text");
    });

    it("never relabels legacy vectors as generated by the current model", () => {
      const legacyData = {
        version: 1,
        dim: 3,
        chunks: [
          {
            path: "src/file1.ts",
            startLine: 1,
            endLine: 10,
            text: "legacy",
            vector: [0.1, 0.2, 0.3],
          },
        ],
      };

      // If loaded without expectedEmbeddingModel, embeddingModel remains undefined
      const store = VectorStore.fromJSON(legacyData);
      assert.equal(store.getEmbeddingModel(), undefined);
    });
  });

  describe("Validation of Vector Data & Containment Invariants", () => {
    it("rejects paths with traversal attempts or absolute paths", () => {
      const badData = {
        version: 2,
        dim: 3,
        embeddingModel: "test-model",
        chunks: [
          {
            path: "../secret.txt",
            startLine: 1,
            endLine: 5,
            text: "traversal",
            vector: [0.1, 0.2, 0.3],
          },
          {
            path: "/etc/passwd",
            startLine: 1,
            endLine: 5,
            text: "absolute",
            vector: [0.1, 0.2, 0.3],
          },
          {
            path: "C:\\Windows\\System32\\drivers",
            startLine: 1,
            endLine: 5,
            text: "windows absolute",
            vector: [0.1, 0.2, 0.3],
          },
          {
            path: "src/valid.ts",
            startLine: 1,
            endLine: 5,
            text: "valid path",
            vector: [0.1, 0.2, 0.3],
          },
        ],
      };

      const store = VectorStore.fromJSON(badData, "test-model");
      assert.equal(store.stats.chunks, 1);
      assert.equal(store.hasFile("src/valid.ts"), true);
      assert.equal(store.hasFile("../secret.txt"), false);
      assert.equal(store.hasFile("/etc/passwd"), false);
    });

    it("rejects chunks with invalid line ranges, empty text, or non-finite vectors", () => {
      const corruptData = {
        version: 2,
        dim: 3,
        embeddingModel: "test-model",
        chunks: [
          {
            path: "src/a.ts",
            startLine: 10,
            endLine: 5, // invalid: endLine < startLine
            text: "bad range",
            vector: [0.1, 0.2, 0.3],
          },
          {
            path: "src/b.ts",
            startLine: 1,
            endLine: 5,
            text: "", // invalid: empty text
            vector: [0.1, 0.2, 0.3],
          },
          {
            path: "src/c.ts",
            startLine: 1,
            endLine: 5,
            text: "nan vector",
            vector: [0.1, NaN, 0.3], // invalid: NaN
          },
          {
            path: "src/d.ts",
            startLine: 1,
            endLine: 5,
            text: "inf vector",
            vector: [0.1, Infinity, 0.3], // invalid: Infinity
          },
          {
            path: "src/e.ts",
            startLine: 1,
            endLine: 5,
            text: "wrong dim",
            vector: [0.1, 0.2], // invalid: dim 2 instead of 3
          },
          {
            path: "src/good.ts",
            startLine: 1,
            endLine: 5,
            text: "export const ok = true;",
            vector: [0.1, 0.2, 0.3],
          },
        ],
      };

      const store = VectorStore.fromJSON(corruptData, "test-model");
      assert.equal(store.stats.chunks, 1);
      assert.equal(store.hasFile("src/good.ts"), true);
    });

    it("revalidates vector unit normalization on load", () => {
      const unnormalizedData = {
        version: 2,
        dim: 2,
        embeddingModel: "test-model",
        chunks: [
          {
            path: "src/math.ts",
            startLine: 1,
            endLine: 2,
            text: "norm test",
            vector: [3, 4], // norm = 5
          },
        ],
      };

      const store = VectorStore.fromJSON(unnormalizedData, "test-model");
      assert.equal(store.stats.chunks, 1);
      const results = store.query([3, 4], 1);
      assert.equal(results.length, 1);
      // Querying with exact direction should produce score 1.0
      assert.ok(Math.abs(results[0].score - 1.0) < 0.0001);
    });

    it("preserves vector dimension contract across clear and remove", () => {
      const store = new VectorStore();
      store.setFile("src/a.ts", [
        { path: "src/a.ts", startLine: 1, endLine: 2, text: "hi", vector: [1, 2, 3, 4] },
      ]);
      assert.equal(store.dimension, 4);

      store.removeFile("src/a.ts");
      assert.equal(store.dimension, 4);

      store.clear();
      assert.equal(store.dimension, 4);
    });

    it("evicts deterministically by oldest mtime when exceeding chunk cap", () => {
      const store = new VectorStore();
      // Add files with different mtimes
      store.setFile(
        "src/old.ts",
        Array.from({ length: 4000 }, (_, i) => ({
          path: "src/old.ts",
          startLine: i,
          endLine: i + 1,
          text: `old line ${i}`,
          vector: [1, 0],
        })),
        1000
      );

      store.setFile(
        "src/med.ts",
        Array.from({ length: 3000 }, (_, i) => ({
          path: "src/med.ts",
          startLine: i,
          endLine: i + 1,
          text: `med line ${i}`,
          vector: [0, 1],
        })),
        2000
      );

      // Now adding 2000 chunks will push total to 9000, exceeding MAX_CHUNKS (8000)
      store.setFile(
        "src/new.ts",
        Array.from({ length: 2000 }, (_, i) => ({
          path: "src/new.ts",
          startLine: i,
          endLine: i + 1,
          text: `new line ${i}`,
          vector: [1, 1],
        })),
        3000
      );

      // Oldest file (src/old.ts with mtime 1000) should be evicted first
      assert.equal(store.hasFile("src/old.ts"), false);
      assert.equal(store.hasFile("src/med.ts"), true);
      assert.equal(store.hasFile("src/new.ts"), true);
      assert.ok(store.stats.chunks <= MAX_CHUNKS);
    });

    it("handles malformed JSON and null data gracefully without crashing", () => {
      assert.equal(VectorStore.fromJSON(null).stats.chunks, 0);
      assert.equal(VectorStore.fromJSON(undefined).stats.chunks, 0);
      assert.equal(VectorStore.fromJSON({}).stats.chunks, 0);
      assert.equal(VectorStore.fromJSON("string").stats.chunks, 0);
      assert.equal(VectorStore.fromJSON({ version: 3, chunks: [] }).stats.chunks, 0);
    });
  });
});

